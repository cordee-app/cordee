def _tool_result_content(result_str, model_id):
    """Build the `role: 'tool'` message content for a tool result.

    Image results (read_file on .png/.jpg/…) become a multi-part
    [text, image_url] content list for vision models — the image is
    delivered as an image part, not as base64 text (regression: gemma
    looped 40 turns on utf-8 mojibake from a PNG read as text and the
    task failed). Text-only models get a note without the payload so a
    single image cannot blow up the context. Everything else is the
    plain string it always was. Returns (content, log_prefix) where
    log_prefix is a short redacted description for logging (never the
    base64).
    """
    try:
        d = json.loads(result_str)
    except (json.JSONDecodeError, TypeError):
        d = None
    is_image = (isinstance(d, dict) and bool(d.get('binary'))
                and isinstance(d.get('mime'), str)
                and d['mime'].startswith('image/'))
    if not is_image:
        return result_str, None
    meta = {'path': d.get('path'), 'binary': True, 'mime': d.get('mime'),
            'size_bytes': d.get('size_bytes')}
    vision = bool(get_cap(model_id).get('vision'))
    log = (f"image {d.get('path')} ({d.get('mime')}, "
           f"{d.get('size_bytes')} bytes, vision={vision})")
    if vision:
        return [
            {'type': 'text', 'text': json.dumps(meta, ensure_ascii=False)},
            {'type': 'image_url',
             'image_url': {'url': f"data:{d['mime']};base64,{d['content']}"}},
        ], log
    return json.dumps({**meta,
                       'note': 'image content not included - this model has no vision'},
                      ensure_ascii=False), log


# Keep image history under the measured gateway limit. 2026-10-15 probes
# against Scaleway: 12 images / 24.5 MB -> 200 OK, 49 images / 95.7 MB ->
# 504 in ~3s. Staying at/below ~20 MB of image payload keeps requests safe.
# Within the budget nothing is compacted at all — placeholders themselves were
# a failure mode: the model (correctly reading an ambiguous marker) spent
# 25 of 60 turns re-reading and re-cropping images it had already seen
# (RP-089 exec 20001269: four generations of the same 'seg' images, zero
# rows written). Compaction now only fires when the payload is genuinely
# too large, and then oldest-first.
_IMG_HISTORY_BUDGET_BYTES = 20_000_000


def _image_payload_size(content):
    """Total base64 payload bytes of the image_url parts in one message."""
    if not isinstance(content, list):
        return 0
    return sum(len(p.get('image_url', {}).get('url') or '')
               for p in content
               if isinstance(p, dict) and p.get('type') == 'image_url')


def _compact_image_history(messages):
    """Placeholder the OLDEST image parts only when the image payload of the
    conversation exceeds the gateway budget.

    Every turn re-sends the whole ``messages`` list; image parts are multi-MB
    data URIs. Unbounded accumulation 504s Scaleway's gateway (measured
    2026-10-15: 49 images / 96 MB fast-fails; RP-087 E4). But compacting
    aggressively was its own failure mode — the placeholders made the model
    distrust its reads and burn its turn budget re-verifying (RP-089
    exec 20001269). So: within the budget, keep EVERY image (no placeholders
    at all); over it, replace the oldest consumed images (never the pending
    batch after the most recent assistant message) until back under budget.
    Idempotent.
    """
    last_asst = -1
    for i, m in enumerate(messages):
        if m.get('role') == 'assistant':
            last_asst = i
    img_msgs = [(i, _image_payload_size(m.get('content')))
                for i, m in enumerate(messages)
                if _image_payload_size(m.get('content')) > 0]
    total = sum(sz for _, sz in img_msgs)
    if total <= _IMG_HISTORY_BUDGET_BYTES or not img_msgs:
        return
    # candidate pool: image messages before the most recent assistant message
    # (the trailing tool batch has not been seen by the model yet)
    protected = {i for i, _ in img_msgs if i > last_asst}
    for idx, sz in img_msgs:  # oldest first
        if total <= _IMG_HISTORY_BUDGET_BYTES:
            break
        if idx in protected:
            continue
        m = messages[idx]
        new_parts = []
        meta_path = None
        replaced = False
        for part in m['content']:
            if (isinstance(part, dict) and part.get('type') == 'text'
                    and meta_path is None):
                try:
                    _d = json.loads(part.get('text') or '')
                    if isinstance(_d, dict) and _d.get('path'):
                        meta_path = _d['path']
                except (json.JSONDecodeError, TypeError):
                    pass
            if isinstance(part, dict) and part.get('type') == 'image_url':
                replaced = True
                name = meta_path or 'an image'
                new_parts.append({'type': 'text', 'text': (
                    f'[HISTORY COMPACTION NOTE — not an error: image {name} was '
                    f'already delivered AND VIEWED in an earlier turn, and your '
                    f'earlier reading of it stands. The copy is not repeated to '
                    f'keep this request small. Do NOT re-read files you have '
                    f'already recorded. Only if you genuinely need to look again: '
                    f'a fresh read_file WILL deliver a new image copy.]')})
            else:
                new_parts.append(part)
        if replaced:
            m['content'] = new_parts
            total -= sz


# Text-history compaction (RP-140, exec 20001493 / task 10001311): tool
# results are the fastest-growing part of `messages` — a long loop that reads
# files and runs commands grows the body until the request itself becomes the
# failure (~200k tokens read-timed-out at 300 s on Scaleway). Elide the OLDEST
# oversized tool-result texts; the most recent ones are the model's current
# evidence and stay verbatim. Same philosophy as _compact_image_history
# above: touch only what is genuinely too large, oldest-first, idempotent.
_TOOL_TEXT_ELIDED_MARK = '[tool result elided'


def _elide_tool_text(text):
    """The stub _compact_text_history replaces an oversized tool result with —
    keeps the first 300 chars so the model can still tell what it was."""
    return (f'{_TOOL_TEXT_ELIDED_MARK} to keep the request small — '
            f'first 300 chars: {text[:300]}…]')


def _compact_text_history(messages, keep_recent=8, cap_chars=10_000):
    """Stub the text of OLD oversized tool results so the request body stays
    sendable. Regression: RP-140 (exec 20001493, task 10001311) — the run
    burned $1.64 and 28 min, then died on a 300 s read timeout because the
    ~200k-token conversation no longer fit the request, and the exception
    propagated as a hard failure that threw the whole in-memory checkpoint
    away.

    Every turn re-sends the whole `messages` list. Tool results older than
    the last `keep_recent` whose text exceeds `cap_chars` are replaced by a
    stub carrying the first 300 chars — the model already consumed them; the
    recent ones (its current evidence) stay verbatim. Multi-part content
    (image tool results) keeps its `image_url` parts untouched and only
    oversized `{'type': 'text'}` parts are stubbed; `role` and `tool_call_id`
    are preserved. Idempotent: a stub is detected by its marker and never
    re-stubbed. Env kill-switch: AINGEL_TOOL_LOOP_TEXT_COMPACT=0 (parsed at
    import into TOOL_LOOP_TEXT_COMPACT above).
    """
    if not TOOL_LOOP_TEXT_COMPACT:
        return
    tool_idx = [i for i, m in enumerate(messages)
                if isinstance(m, dict) and m.get('role') == 'tool']
    # everything except the last `keep_recent` tool messages; keep_recent<=0
    # means no protection at all ([:-0] would slice to empty, hence the guard)
    old = tool_idx[:-keep_recent] if keep_recent > 0 else tool_idx
    for i in old:
        m = messages[i]
        content = m.get('content')
        if isinstance(content, str):
            if len(content) > cap_chars and not content.startswith(_TOOL_TEXT_ELIDED_MARK):
                m['content'] = _elide_tool_text(content)
        elif isinstance(content, list):
            # image tool results: stub only the oversized text parts, never
            # the image_url parts (a re-read is the only way to re-deliver one)
            new_parts = None
            for j, part in enumerate(content):
                if not (isinstance(part, dict) and part.get('type') == 'text'):
                    continue
                t = part.get('text') or ''
                if len(t) > cap_chars and not t.startswith(_TOOL_TEXT_ELIDED_MARK):
                    if new_parts is None:
                        new_parts = list(content)
                    new_parts[j] = {'type': 'text', 'text': _elide_tool_text(t)}
            if new_parts is not None:
                m['content'] = new_parts


def _run_openai_tool_loop(*, provider_label, api_url, api_key, wire_model,
                          model_id, prompt, max_tokens, max_turns, project_path,
                          exec_id=None):
    """Shared OpenAI-compatible function-calling loop used by both Scaleway and
    Ollama Cloud. Uses `requests` directly (not the OpenAI client) to avoid Pydantic
    serialization quirks that make some OpenAI-compatible backends reject multi-turn
    tool-call bodies. Returns (text, tok_in, tok_out, cost_usd).

    `provider_label` is only used for logging/error text. Tool schemas, dispatch, and
    the Phase 7.2 read-back nudge are identical across providers.
    """
    import agent_tools
    import requests as _requests

    use_tools = bool(project_path and os.path.isdir(project_path))
    _log.info(
        "%s API call: superagent_id=%s wire_id=%s tools=%s",
        provider_label, model_id, wire_model, use_tools,
    )

    headers = {
        'Authorization': f'Bearer {api_key}',
        'Content-Type': 'application/json',
    }

    def _post(body):
        raw = json.dumps(body, ensure_ascii=False).encode('utf-8')

        @retry(
            stop=stop_after_attempt(getattr(agent_config, 'SCW_HTTP_RETRY_ATTEMPTS', 3)),
            wait=wait_exponential(multiplier=1, min=10, max=30),
            retry=retry_if_exception_type((_requests.exceptions.ReadTimeout,
                                           _requests.exceptions.ConnectionError,
                                           _EmptyResponseError,
                                           _TransientHTTPError)),
            reraise=True,
        )
        def _do_post():
            # Read-timeout cap for pausable runs (regression: RP-140,
            # exec 20001493) — a 300 s read timeout inside a 2700 s time
            # budget lets one stalled call silently eat the whole segment.
            # Cap the read timeout to the REMAINING budget, floored at 60 s
            # so a nearly-spent budget doesn't turn every call into a fast
            # connection failure; never above the historical 300. Non-pausable
            # callers keep exactly 300. _pause/_t_start are assigned after
            # _post is defined (they live in the try: below), so guard the
            # read with NameError — the wrapper is only ever invoked once
            # they are bound, but stay safe anyway.
            try:
                _ps, _ts = _pause, _t_start
            except NameError:
                _ps, _ts = None, None
            if _ps:
                remaining = _ps['time_budget_s'] - (time.time() - _ts)
                timeout = max(60, min(300, remaining))
            else:
                timeout = 300
            try:
                resp = _requests.post(api_url, headers=headers, data=raw, timeout=timeout)
            except (_requests.exceptions.ReadTimeout,
                    _requests.exceptions.ConnectionError) as e:
                # Big-body fast-fail (regression: RP-140, exec 20001493): a
                # >400 KB body that just blew its read timeout will not
                # succeed unchanged on the next attempt — the 3x tenacity
                # retry of the identical oversized body wasted 15.5 min
                # before the hard failure. _NoRetryProviderError is NOT in
                # the @retry tuple above, so this surfaces immediately
                # (and the pausable wrapper converts it to a resumable
                # pause instead of a total loss).
                if len(raw) > _BIG_BODY_NO_RETRY_BYTES:
                    raise _NoRetryProviderError(
                        f"{type(e).__name__} on a {len(raw)}-byte request body "
                        f"(no retry — the unchanged body just blew its read "
                        f"timeout): {e}")
                raise
            if resp.status_code != 200:
                # 5xx and 429 are transient (LB/upstream hiccup, rate limit,
                # reasoning-model stream timeout). 4xx are permanent and must
                # surface immediately — retrying a 400 payload-validation error
                # wastes three attempts and hides the real cause.
                if resp.status_code >= 500 or resp.status_code == 429:
                    raise _TransientHTTPError(
                        f"Error code: {resp.status_code} - {resp.text or resp.reason}")
                raise Exception(f"Error code: {resp.status_code} - {resp.text or resp.reason}")
            # Scaleway's envoy LB occasionally returns HTTP 200 with an empty
            # body (upstream hiccup / connection drop mid-stream). `resp.json()`
            # then raises JSONDecodeError("Expecting value: line 1 column 1
            # (char 0)") which, before this guard, failed the whole execution
            # (regression: task #10001058). Treat it as a transient transport
            # error so the @retry above re-issues the call.
            try:
                return resp.json()
            except ValueError:
                # `resp.text` may be absent on minimal fakes (tests); fall back
                # to getattr so we never mask the original parse error.
                body = getattr(resp, 'text', '') or ''
                if not body.strip():
                    raise _EmptyResponseError(
                        f"{provider_label} returned 200 with empty body (model={wire_model})")
                raise _EmptyResponseError(
                    f"{provider_label} returned 200 with non-JSON body "
                    f"(model={wire_model}, first 80 bytes={body[:80]!r})")

        return _do_post()

    # Usage accumulators live OUTSIDE the try: an exception raised before the
    # per-turn loop first runs (prompt sanitize, first POST) must still find
    # them bound so the except handler below can attach the run's usage to the
    # re-raised exception. Inside the try they died with the frame's exception,
    # which is how a 40-turn Scaleway run once lost 1.23M paid-for tokens.
    tok_in_total = tok_out_total = 0

    try:
        # Sanitize prompt: strip null bytes and invalid UTF-8 sequences.
        prompt = prompt.encode('utf-8', 'replace').decode('utf-8')

        messages = [{'role': 'user', 'content': prompt}]
        _pause = current_pause_scope()
        _resume = (_pause or {}).get('resume')
        # Usage of earlier parts of a resumed run: shown in live progress so the
        # row's totals are cumulative; the return value stays this part's only
        # (route() meters each call once).
        base_in = int((_resume or {}).get('tokens_input') or 0)
        base_out = int((_resume or {}).get('tokens_output') or 0)
        _t_start = time.time()
        if _resume:
            messages = list(_resume['messages'])
            # RP-140 (exec 20001493): a resumed checkpoint can already carry
            # the huge tool-result history that killed the previous segment —
            # elide the old oversized results BEFORE the first request of this
            # segment repeats the same 300 s read timeout.
            _compact_text_history(messages)
            note = (_resume.get('note') or '').strip()
            messages.append({'role': 'user', 'content': (
                'The user chose to continue this run for another block of turns. '
                'Carry on from where you stopped; do not redo finished work.'
                + (f'\n\nNote from the user: {note}' if note else ''))})
        _guide = current_guide_scope()
        tools = agent_tools.TOOL_SCHEMAS if use_tools else None
        if tools and _guide:
            tools = [t for t in tools if t['function']['name'] in _GUIDE_LOOP_TOOLS]

        text = ''
        # Agentic transcript: the model's real "output" is the whole session
        # (narration + the tool actions it took), not just the last message.
        # We accumulate it here so the Exec Log "View" shows what actually
        # happened. Action lines use plain `→ tool` markers (no <bash>/<invoke>
        # tag pairs) so they never trip the Phase 7.2 simulation detector.
        transcript = []
        if _resume:
            transcript = list(_resume.get('transcript') or [])
            part = int(_resume.get('segments') or 1) + 1
            note = (_resume.get('note') or '').strip()
            transcript.append(f'--- ▶ Continued by the user (part {part})'
                              + (f': "{note}"' if note else '') + ' ---')

        def _record_step(narration, tool_calls):
            narration = _flatten_content(narration)
            if narration.strip():
                transcript.append(narration.strip())
            lines = []
            for _tc in tool_calls or []:
                _fn = _tc.get('function', {}).get('name', 'tool')
                try:
                    _a = json.loads(_tc.get('function', {}).get('arguments') or '{}')
                except (json.JSONDecodeError, TypeError):
                    _a = {}
                _p = _a.get('path')
                lines.append(f'→ `{_fn}`' + (f' `{_p}`' if _p else ''))
            if lines:
                transcript.append('\n'.join(lines))

        def _emit_progress():
            """Write the running token totals to the execution row (mid-run live
            progress). Best-effort: a DB/SSE hiccup must never break the run."""
            if not exec_id:
                return
            try:
                import agent_db as _db
                _db.update_execution_tokens(exec_id, base_in + tok_in_total,
                                            base_out + tok_out_total,
                                            project_path=project_path)
            except Exception:
                pass

        def _pause_now(reason, turns_used):
            """Ask the model for its status (no tools), then raise LimitReached
            with a checkpoint. Replaces the forced "answer now" call for
            pausable runs: E7 spent its last call writing "Let me now write the
            deliverable." and the work was lost."""
            nonlocal tok_in_total, tok_out_total
            what = 'turn' if reason == 'turns' else 'time'
            messages.append({'role': 'user', 'content': _STATUS_AT_LIMIT_PROMPT.format(what=what)})
            status_text = ''
            try:
                data = _post({'model': wire_model, 'messages': messages,
                              'max_tokens': min(max_tokens, 2048)})
                usage = data.get('usage', {}) or {}
                tok_in_total += usage.get('prompt_tokens', 0) or 0
                tok_out_total += usage.get('completion_tokens', 0) or 0
                _emit_progress()
                choices = data.get('choices') or []
                status_text = _flatten_content(
                    choices[0].get('message', {}).get('content') if choices else '').strip()
                status_text = _STRIP_TOOL_MARKUP_RE.sub('', status_text).strip()
            except Exception as e:  # the pause must not fail on its status call
                _log.warning('%s status call at the %s limit failed: %s', provider_label, what, e)
            if status_text:
                messages.append({'role': 'assistant', 'content': status_text})
            transcript.append(f'--- ⏸ Paused at the {what} limit ({turns_used} turns, '
                              f'{int(time.time() - _t_start)} s) ---'
                              + (f'\n\n**Model status:**\n{status_text}' if status_text else ''))
            raise LimitReached(reason, {
                'messages': messages,
                'transcript': transcript,
                'reason': reason,
                'turns': turns_used,
                'elapsed_s': int(time.time() - _t_start),
                'status_text': status_text,
                'segment_tokens_input': tok_in_total,
                'segment_tokens_output': tok_out_total,
                'model_id': model_id,
                'max_turns': max_turns,
            })

        # Current turn number for the provider-failure pause checkpoint below.
        # A one-slot cell: _force_final_text runs both mid-loop and from the
        # post-loop else-branch, where the for-variable is not a reliable
        # closure read.
        _turn_now = [0]

        def _post_pausable(body, turn_no):
            """_post + convert a hard provider failure into a resumable pause.

            Regression: RP-140 (exec 20001493, task 10001311) — the
            conversation grew to ~200k tokens, api.scaleway.ai read-timed-out
            at 300 s, and the ReadTimeout propagated as a hard failure: the
            whole in-memory `messages` checkpoint (~$1.64 of paid work) was
            thrown away, because the pause machinery only fired at turn/time
            checkpoints between turns, never on provider errors. Now a
            transport failure (read timeout, connection error, transient
            5xx/429, or the big-body no-retry error) in a pausable run with
            real work behind it becomes LimitReached('provider_error')
            instead: the checkpoint mirrors _pause_now's shape (status_text
            is '' — there is no status call to make here; all consumers do
            `or ''`), and the outer except below attaches the segment's
            usage to the exception. Turn 0 with an empty transcript has
            nothing to lose, and non-pausable callers (chats, H3, batch)
            keep the legacy hard-failure behaviour: re-raise unchanged.
            """
            try:
                return _post(body)
            except (_requests.exceptions.ReadTimeout,
                    _requests.exceptions.ConnectionError,
                    _TransientHTTPError,
                    _NoRetryProviderError) as e:
                if not current_pause_scope() or (turn_no <= 0 and not transcript):
                    raise
                # The oversized body was likely the failure itself (RP-140):
                # shrink the old tool-result history so the checkpoint — and
                # the resume's first request — is sendable again.
                _compact_text_history(messages)
                _err = ' '.join(str(e).split())[:160] or type(e).__name__
                transcript.append(f'--- ⏸ Paused after a provider failure ({_err}) ---')
                raise LimitReached('provider_error', {
                    'messages': messages,
                    'transcript': transcript,
                    'reason': 'provider_error',
                    'turns': turn_no,
                    'elapsed_s': int(time.time() - _t_start),
                    'status_text': '',
                    'segment_tokens_input': tok_in_total,
                    'segment_tokens_output': tok_out_total,
                    'model_id': model_id,
                    'max_turns': max_turns,
                })

        def _force_final_text(mt=None):
            """One-shot forced synthesis when the loop ends without a usable final
            answer (either max_turns exhausted, or the model returned an empty
            final-text turn after real tool work). Sends a "wrap it up" user
            message (no tools bound so the model can't call more) and strips any
            residual tool-call markup from the reply. Returns '' if the model
            still produced nothing.
            """
            nonlocal tok_in_total, tok_out_total
            messages.append({'role': 'user', 'content': 'Based on all the information gathered above, provide your complete response now.'})
            # Pausable wrapper (RP-140): a provider failure here would also
            # torch the whole checkpoint — convert it to a pause when the
            # caller opted in.
            data = _post_pausable({'model': wire_model, 'messages': messages, 'max_tokens': mt if mt is not None else max_tokens}, _turn_now[0])
            usage = data.get('usage', {})
            tok_in_total  += usage.get('prompt_tokens', 0) or 0
            tok_out_total += usage.get('completion_tokens', 0) or 0
            _emit_progress()
            choices = data.get('choices') or []
            t = _flatten_content(choices[0].get('message', {}).get('content') if choices else '').strip()
            if t:
                t = _STRIP_TOOL_MARKUP_RE.sub('', t).strip()
            return t

        hit_turn_limit = False
        for turn in range(max_turns):
            _turn_now[0] = turn  # for _force_final_text's provider-failure pause
            # Cancel check: the /cancel endpoint flips the execution row to
            # 'failed' and kills any child PID, but this loop runs in-process
            # (no child PID to signal). Without this check a cancelled
            # execution keeps burning turns for minutes and the late-returning
            # run used to mark the user-reset task 'done' (regression: task
            # #10001124). Raises ExecutionCancelledError, which run_task
            # handles as a clean stop (and which is deliberately NOT in the
            # HTTP retry lists, so retries don't fight the cancel).
            if _execution_cancelled(exec_id, project_path):
                raise ExecutionCancelledError('execution cancelled during tool loop')
            # Soft time budget (pausable runs only), checked between turns so
            # the pause lands on a clean point.
            if _pause and turn > 0 and time.time() - _t_start >= _pause['time_budget_s']:
                _pause_now('time', turn)

            # Image-history compaction: consumed image parts are multi-MB
            # data URIs re-sent on every turn — without this the body grows
            # past Scaleway's gateway limit mid-run and 504s (RP-087 E4).
            # Keeps the pending (not yet answered) tool batch intact.
            _compact_image_history(messages)

            body = {'model': wire_model, 'messages': messages, 'max_tokens': max_tokens}
            if tools:
                body['tools'] = tools

            # Pausable wrapper (regression: RP-140, exec 20001493): a hard
            # provider failure mid-loop must pause with a checkpoint, not
            # torch ~$1.64 of in-memory work as a hard failure.
            data = _post_pausable(body, turn)

            usage = data.get('usage', {})
            tok_in_total  += usage.get('prompt_tokens', 0) or 0
            tok_out_total += usage.get('completion_tokens', 0) or 0
            _emit_progress()

            choices = data.get('choices') or []
            if not choices:
                break

            choice = choices[0]
            finish_reason = choice.get('finish_reason')
            msg = choice.get('message', {})

            # Model wants to call tools
            if finish_reason == 'tool_calls' and msg.get('tool_calls'):
                # Only pass back fields the backend needs — strip reasoning/annotations/audio
                # that inflate the body and can confuse strict JSON parsers on later turns.
                asst = {'role': 'assistant', 'tool_calls': msg['tool_calls']}
                if msg.get('content'):
                    asst['content'] = msg['content']
                messages.append(asst)
                _record_step(msg.get('content'), msg['tool_calls'])
                for tc in msg['tool_calls']:
                    fn_name = tc['function']['name']
                    try:
                        args = json.loads(tc['function']['arguments'])
                    except (json.JSONDecodeError, TypeError):
                        args = {}
                    result_str = (_guide_dispatch(_guide, fn_name, args, project_path) if _guide
                                  else agent_tools.dispatch(fn_name, args, project_path))
                    content, log_prefix = _tool_result_content(result_str, model_id)
                    if log_prefix is not None:
                        # Image result: log the redacted description — the usual
                        # result_str[:120] slice would be pure base64.
                        _log.info('tool result for %s: %s', fn_name, log_prefix)
                    else:
                        _log.info('tool result for %s: %s…', fn_name, result_str[:120])
                    messages.append({
                        'role': 'tool',
                        'tool_call_id': tc['id'],
                        'content': content,
                    })
                    # Phase 7.2 — verify writes/patches by reading back
                    if fn_name in ('write_file', 'patch_file'):
                        ver_path = args.get('path')
                        if ver_path:
                            messages.append({
                                'role': 'user',
                                'content': (
                                    f'You just called {fn_name} on {ver_path}. '
                                    'Now call read_file with the same path to verify '
                                    'the file on disk matches your intent before continuing.'
                                ),
                            })
                continue  # next turn with tool results

            # Final text response
            text = _flatten_content(msg.get('content')).strip()
            if text:
                transcript.append(text)
            # Truncation retry — in-turn re-issue at raised budget (does NOT
            # increment the `for turn in range(40)` counter). Retries any
            # truncated final (empty or non-empty) when the model cap allows
            # headroom; the 4 reasoning models capped at 16384 have no headroom
            # when called at their cap (retry is a no-op).
            if finish_reason == 'length':
                cap_max = int(get_cap(model_id).get('max_tokens') or max_tokens)
                effective_mt = effective_max_tokens(model_id, cap_max)
                if effective_mt > max_tokens:
                    _log.warning(
                        "%s truncated (length) at max_tokens=%s — retrying at %s",
                        provider_label, max_tokens, effective_mt,
                    )
                    pre_retry_text = text
                    body2 = {**body, 'max_tokens': effective_mt}
                    # Pausable wrapper (RP-140): same provider-failure →
                    # pause conversion as the main call site above.
                    data2 = _post_pausable(body2, turn)
                    u2 = data2.get('usage', {}) or {}
                    tok_in_total += u2.get('prompt_tokens', 0) or 0
                    tok_out_total += u2.get('completion_tokens', 0) or 0
                    _emit_progress()
                    choices2 = data2.get('choices') or []
                    msg2 = choices2[0].get('message', {}) if choices2 else {}
                    text2 = _flatten_content(msg2.get('content')).strip() if msg2 else ''
                    finish_reason2 = finish_reason
                    try:
                        if choices2:
                            finish_reason2 = choices2[0].get('finish_reason') or finish_reason
                    except Exception:
                        pass
                    # Adopt the retry only if it is non-empty AND actually
                    # better: not truncated, or longer than the truncated text.
                    if text2 and (finish_reason2 != 'length' or len(text2) > len(text)):
                        text = text2
                        if pre_retry_text and transcript and transcript[-1] == pre_retry_text:
                            transcript[-1] = text2
                        else:
                            transcript.append(text2)
                        # adopt retry finish_reason for the marker check below
                        finish_reason = finish_reason2
            if finish_reason == 'length':
                _log.warning(
                    "%s response truncated at max_tokens=%d model=%s turn=%d",
                    provider_label, max_tokens, wire_model, turn,
                )
            # If the model returned an empty final text but the session already
            # accumulated real tool work, do NOT silently break and ship the raw
            # transcript (which ends mid-flow at a `→ tool` line). Force a proper
            # synthesis so the deliverable reads as complete. Mirrors the
            # max-turns recovery below. Regression: task #12 (a client project).
            if not text and len(transcript) >= 1:
                _log.warning(
                    "%s model %s returned empty final text on turn %d after %d transcript entries — forcing final synthesis",
                    provider_label, wire_model, turn, len(transcript),
                )
                _forced = _force_final_text(mt=effective_mt if 'effective_mt' in locals() else None)
                if _forced:
                    transcript.append(_forced)
                    text = _forced
            if finish_reason == 'length' and text and transcript and text == transcript[-1]:
                text = text + TRUNCATION_MARKER
                transcript[-1] = text
                _log.warning("%s shipping truncated (but non-empty) deliverable — appending marker", provider_label)
            break

        else:
            if _pause:
                _log.warning("%s tool loop hit max turns (%d) for model=%s — pausing for the user",
                             provider_label, max_turns, wire_model)
                _pause_now('turns', max_turns)
            _log.warning("%s tool loop hit max turns (%d) for model=%s — forcing final text call", provider_label, max_turns, wire_model)
            _forced = _force_final_text()
            if not _forced:
                raise RuntimeError(
                    f"{provider_label} model {wire_model} exhausted {max_turns} tool turns "
                    "and produced no final text response. "
                    "The model kept calling tools without delivering a final answer. "
                    "Consider using a different model or reducing the number of file reads."
                )
            transcript.append(_forced)
            text = _forced
            hit_turn_limit = True

        # The deliverable is the whole agentic session. When the model narrated
        # and/or took tool actions across turns, return that transcript so the
        # output view is readable; otherwise fall back to the single final text.
        if len(transcript) > 1:
            text = '\n\n'.join(t for t in transcript if t).strip()
        if hit_turn_limit:
            text += (f"\n\n---\n⚠️ **{TOOL_TURN_LIMIT_MARKER} ({max_turns} turns) before "
                     "the model finished.** The answer above was forced; the task may be incomplete.")

        pricing = agent_config.get_pricing(model_id)
        cost = round(
            tok_in_total * pricing['input'] / 1_000_000 +
            tok_out_total * pricing['output'] / 1_000_000,
            6,
        ) if pricing else 0.0

        return text, tok_in_total, tok_out_total, cost

    except Exception as exc:
        if isinstance(exc, LimitReached):
            _log.info("%s run paused at its %s limit", provider_label, exc.reason)
        else:
            _log.error("%s API error: %s", provider_label, exc)
        # Usage must ride out of the loop ON the exception: route() meters
        # failed-but-paid calls from these attributes, and the executor writes
        # them to the executions row. Before this, a run that raised mid-loop
        # recorded its entire accumulated usage nowhere (regression: a
        # gemma-4-26b run exhausted 40 tool turns on 1.23M input tokens and
        # was finished as 0/0/$0.00). Harmless zeros when nothing completed.
        exc.tokens_input = tok_in_total
        exc.tokens_output = tok_out_total
        raise
    finally:
        _log.info("%s API call ended: model=%s", provider_label, wire_model)


