def _inside(path, root):
    path, root = os.path.realpath(path), os.path.realpath(root)
    return path == root or path.startswith(root + os.sep)


# Tools the in-process loop offers in Guide mode. No bash, no patch_file;
# write_file only inside the scope's folder (checked in _guide_dispatch).
_GUIDE_LOOP_TOOLS = frozenset({'list_files', 'list_working_docs', 'read_file', 'write_file',
                               'get_project_memory', 'rag_query', 'web_fetch'})


def _guide_dispatch(scope, fn_name, args, project_path):
    """agent_tools.dispatch with the Guide-mode limits applied."""
    import agent_tools
    if fn_name not in _GUIDE_LOOP_TOOLS:
        return json.dumps({'error': f'{fn_name} is not available to the Guide (read-only).'})
    if fn_name == 'write_file':
        target = os.path.join(project_path, str(args.get('path') or ''))
        if not _inside(target, scope['write_dir']):
            rel = os.path.relpath(scope['write_dir'], project_path)
            return json.dumps({'error': f'The Guide can write only inside {rel}/. '
                                        'Propose other changes to the user instead.'})
        # agent_tools.write_file only allows Working Documents / task outputs —
        # exactly what the Guide must not touch — so write the note directly.
        content = str(args.get('content') or '')
        try:
            os.makedirs(os.path.dirname(os.path.realpath(target)), exist_ok=True)
            with open(target, 'w', encoding='utf-8') as f:
                f.write(content)
        except OSError as e:
            return json.dumps({'error': f'write failed: {e}'})
        return json.dumps({'ok': True, 'path': os.path.relpath(os.path.realpath(target), project_path),
                           'bytes': len(content.encode('utf-8'))})
    return agent_tools.dispatch(fn_name, args, project_path)


_VIBE_AGENTS_DIR = os.path.join(os.path.expanduser('~'), '.vibe', 'agents')


def _ensure_vibe_guide_agent(write_dir):
    """Write (once) a Vibe agent profile that is read-only except ``write_dir``.

    Verified against Vibe 2.26 headless without --auto-approve: write_file/edit
    outside the allowlist, every bash command (allowlists don't apply to the
    unified harness shell) and subagents are denied; read_file and grep work.
    One profile per folder, named by a hash of the path.
    """
    write_dir = os.path.realpath(write_dir)
    name = 'cordee-guide-' + hashlib.sha1(write_dir.encode('utf-8')).hexdigest()[:12]
    pattern = json.dumps(os.path.join(write_dir, '*'))
    body = (
        '# Generated by Cordée (agent_router._ensure_vibe_guide_agent). Do not edit.\n'
        'display_name = "Cordée Guide (read-only)"\n'
        f'description = {json.dumps("Read-only; writes only in " + write_dir)}\n'
        'safety = "safe"\n'
        'disabled_tools = ["exit_plan_mode", "task"]\n'
        '[tools.write_file]\npermission = "never"\n'
        f'allowlist = [{pattern}]\n'
        '[tools.edit]\npermission = "never"\n'
        f'allowlist = [{pattern}]\n'
        '[tools.bash]\npermission = "never"\n'
    )
    os.makedirs(_VIBE_AGENTS_DIR, exist_ok=True)
    path = os.path.join(_VIBE_AGENTS_DIR, name + '.toml')
    try:
        with open(path, encoding='utf-8') as f:
            if f.read() == body:
                return name
    except OSError:
        pass
    tmp = path + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        f.write(body)
    os.replace(tmp, path)
    return name

