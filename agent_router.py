def _vibe_continuation_block(resume, room=4000):
    """Prompt suffix for a continued Vibe block (fresh session, replayed task).

    The Vibe CLI cannot resume a session headlessly, so the continuation
    re-sends the task prompt with a summary of the previous block appended:
    the model sees its own narration and tool calls, then inspects the files
    left on the (re-checked-out) task branch. ``room`` is a byte budget for the
    whole block; the oldest transcript lines are dropped first."""
    part = int((resume or {}).get('segments') or 1) + 1
    note = ((resume or {}).get('note') or '').strip()
    lines = [str(t).strip() for t in ((resume or {}).get('transcript') or [])
             if str(t).strip()]
    head = (f'\n\n---\nCONTINUATION — part {part} of a task that stopped at its '
            'turn limit.\nThe task above was already started in this project. '
            'Work already done:\n\n')
    tail = ('\n\nCarry on from where it stopped: inspect the files on disk, do '
            'not redo finished work, and finish the remaining steps.')
    if note:
        tail += f'\n\nNote from the user: {note}'
    body = '\n'.join(lines)
    budget = max(200, int(room or 4000) - len((head + tail).encode('utf-8')))
    if len(body.encode('utf-8')) > budget:
        cut = body.encode('utf-8')[-budget:].decode('utf-8', errors='ignore')
        body = '…\n' + cut
    return head + (body or '(no steps recorded)') + tail


def _vibe_journal_transcript(session_dir, skip_results=0):
    """(narration + `→ tool` lines, action_result count) from a Vibe journal.

    The journal is the only record that survives a SIGKILLed run and the only
    place with real tool calls. ``skip_results`` drops the action_result
    records already covered by the checkpoint transcript (a resumed run)."""
    import glob
    out, seen = [], 0
    try:
        for jf in sorted(glob.glob(os.path.join(session_dir, 'journal', '*.jsonl'))):
            with open(jf, encoding='utf-8') as f:
                for line in f:
                    try:
                        rec = json.loads(line)
                    except ValueError:
                        continue
                    if rec.get('type') != 'action_result':
                        continue
                    seen += 1
                    if seen <= skip_results:
                        continue
                    res = ((rec.get('payload') or {}).get('result') or {}).get('result')
                    if not isinstance(res, dict):
                        continue
                    for p in res.get('parts') or []:
                        if not isinstance(p, dict) or p.get('type') == 'reasoning':
                            continue
                        txt = (p.get('text') or '').strip()
                        if not txt:
                            for c in (p.get('content') or []):
                                if isinstance(c, dict) and (c.get('text') or '').strip():
                                    txt = (c['text'] or '').strip()
                                    break
                        if txt:
                            out.append(txt)
                        if p.get('type') == 'tool_call':
                            try:
                                args = json.loads(p.get('arguments_json') or '{}')
                            except (ValueError, TypeError):
                                args = {}
                            target = (args.get('command') or args.get('path')
                                      or args.get('file_path') or '')
                            action = f"→ `{p.get('name') or 'tool'}`"
                            if target:
                                action += f' `{str(target)[:80]}`'
                            out.append(action)
    except Exception as e:
        _log.warning('vibe journal transcript failed: %s', e)
    return out, seen


def _vibe_status_line(seg, text=''):
    """Human status for a Vibe pause report.

    Prefers the CLI's last assistant message; a run stopped on a bare tool call
    has none, so fall back to the last narration line, then to the last action.
    """
    status = (text or '').strip()
    if status:
        return status
    for line in reversed(seg or []):
        if not line.startswith('→ '):
            return line
    for line in reversed(seg or []):
        if line.startswith('→ '):
            return f'Last action: {line}'
    return ''


def _pick_vibe_session(vibe_usage, root=None):
    """The resume handle: newest of the run's session folders.

    A retried run can leave several folders (tenacity re-spawns the CLI); the
    live conversation is in the most recently bumped one."""
    ids = [s for s in ((vibe_usage or {}).get('sessions') or []) if s]
    if not ids:
        return None
    if len(ids) == 1:
        return ids[0]

    def _bumped(sid):
        try:
            with open(os.path.join(root or VIBE_SESSION_ROOT, sid, 'meta.json'),
                      encoding='utf-8') as f:
                m = json.load(f)
            return m.get('bumped_at') or m.get('end_time') or m.get('start_time') or ''
        except Exception:
            return ''
    return max(ids, key=_bumped)


def _cli_checkpoint(*, kind, session_id, reason, turns, elapsed_s, status_text,
                    transcript, model_id, seg_in, seg_out):
    """The LimitReached checkpoint for a CLI route.

    Keeps the tool-loop contract (reason/turns/elapsed_s/status_text/transcript/
    usage) and adds ``cli_session`` — ``kind`` ('claude' resumes the CLI's own
    session; 'vibe' replays the task prompt with a continuation block) plus the
    session id for diagnostics. ``messages`` stays present-but-empty: a CLI
    checkpoint is never resumed by the tool loop (the executor pins the row's
    model on resume)."""
    return {
        'reason': reason,
        'turns': max(0, int(turns or 0)),
        'elapsed_s': max(0, int(elapsed_s or 0)),
        'status_text': (status_text or '').strip()[:4000],
        'transcript': [str(t) for t in (transcript or []) if t],
        'model_id': model_id,
        'messages': [],
        'cli_session': {'kind': kind, 'session_id': session_id},
        'segment_tokens_input': int(seg_in or 0),
        'segment_tokens_output': int(seg_out or 0),
    }


def _raise_limit(reason, checkpoint, seg_in, seg_out):
    """Raise LimitReached with this segment's usage attached.

    route()'s choke point meters failed calls from exc.tokens_input/output
    (agent_router.py route()), so a paused CLI segment is billed like a
    paused tool-loop segment."""
    exc = LimitReached(reason, checkpoint)
    exc.tokens_input = int(seg_in or 0)
    exc.tokens_output = int(seg_out or 0)
    raise exc


def cleanup_cli_session(kind, session_id):
    """Delete a run's persisted CLI session when its checkpoint is dropped.

    Claude task runs now persist a session per execution (that is what makes
    resume possible); it must not accumulate forever. Vibe sessions are left
    alone — they are the usage telemetry store _vibe_session_usage reads."""
    if not session_id or kind != 'claude':
        return
    try:
        import glob
        pat = os.path.join(os.path.expanduser('~'), '.claude', 'projects', '*',
                           f'{session_id}.jsonl')
        for p in glob.glob(pat):
            try:
                os.remove(p)
            except OSError:
                pass
    except Exception as e:
        _log.warning('claude session cleanup failed: %s', e)


class ExecutionCancelledError(Exception):
    """Raised when a provider subprocess is killed because the execution was
    cancelled. Deliberately NOT a RuntimeError subclass (and therefore not in
    VIBE_CLI_RETRYABLE_ERRORS) so the tenacity retry loop stops instead of
    re-spawning the CLI after a cancel."""


def _execution_cancelled(exec_id, project_path=None):
    """True if the execution row is no longer 'running' (i.e. it was cancelled
    or otherwise finished while the provider subprocess was in flight). Used to
    abort the CLI retry loop so a cancelled task does not keep re-running."""
    if exec_id is None:
        return False
    try:
        import agent_db as db
        info = db.get_execution_pid(exec_id, project_path=project_path)
        return info is None or info.get('status') != 'running'
    except Exception:
        return False


def _cost(model_id, tok_in, tok_out):
    """Per-token cost from MODELS. Does not account for Anthropic cache
    read/write pricing — cache tokens are billed at the full input rate
    (conservative upper bound). See PRICING comment in agent_config.py."""
    m = MODELS.get(model_id, MODELS[DEFAULT_MODEL])
    return round((tok_in * m['cost_input'] + tok_out * m['cost_output']) / 1_000_000, 6)


def _pricing_cost(model_id, tok_in, tok_out):
    """Per-token cost from PRICING (fuzzy fallback). Same cache-pricing
    limitation as _cost() — see agent_config.py PRICING comment."""
    pricing = agent_config.get_pricing(model_id)
    if pricing:
        return round((tok_in * pricing['input'] + tok_out * pricing['output']) / 1_000_000, 6)
    _log.warning("No pricing configured for model=%s; recording OpenAI PAYG cost as 0.0", model_id)
    return 0.0


VIBE_SESSION_ROOT = os.path.expanduser('~/.vibe/logs/session/unified')


def _vibe_session_usage(project_path, prompt, t0, t1, root=None):
    """Token usage of the Vibe session(s) this call started, or None.

    Vibe >= 2.26 keeps one folder per session under ``unified/<uuid>/``. Its
    meta.json has no stats block; each model call writes an ``action_result``
    journal record carrying ``usage``. Picking "the newest session_* folder"
    (the pre-2.26 layout) froze every run at one old session's numbers from
    2026-10-05 on. A session is ours when it started in this project during the
    call; with several candidates (a chat and a task in the same project, or
    the retry loop), the ones whose first user message is our prompt win.

    Returns {calls, input, cached, output, last_has_text, sessions}.
    """
    import glob
    from datetime import datetime
    root = root or VIBE_SESSION_ROOT
    try:
        proj_real = os.path.realpath(project_path)
    except Exception:
        return None
    needle = (prompt or '').strip()[:300]
    candidates = []
    for d in glob.glob(os.path.join(root, '*')):
        try:
            if os.path.getmtime(d) < t0 - 5:
                continue
            with open(os.path.join(d, 'meta.json'), encoding='utf-8') as f:
                meta = json.load(f)
            start = datetime.fromisoformat(meta['start_time']).timestamp()
            origin = os.path.realpath(meta.get('origin_directory') or '')
        except Exception:
            continue
        if origin == proj_real and t0 - 5 <= start <= t1 + 5:
            candidates.append(d)
    if not candidates:
        return None

    def _strings(o):
        if isinstance(o, str):
            yield o
        elif isinstance(o, dict):
            for v in o.values():
                yield from _strings(v)
        elif isinstance(o, list):
            for v in o:
                yield from _strings(v)

    def _records(d):
        for jf in sorted(glob.glob(os.path.join(d, 'journal', '*.jsonl'))):
            with open(jf, encoding='utf-8') as f:
                for line in f:
                    try:
                        yield json.loads(line)
                    except ValueError:
                        continue

    def _has_prompt(d):
        if not needle:
            return False
        for rec in _records(d):
            if any(needle in s for s in _strings(rec)):
                return True
        return False

    mine = [d for d in candidates if _has_prompt(d)]
    if not mine:
        if len(candidates) != 1:
            return None   # ambiguous — never attribute another run's usage
        mine = candidates
    out = {'calls': 0, 'input': 0, 'cached': 0, 'output': 0,
           'last_has_text': False, 'last_finish_reason': '',
           'sessions': [os.path.basename(d) for d in mine]}
    for d in mine:
        for rec in _records(d):
            if rec.get('type') != 'action_result':
                continue
            res = ((rec.get('payload') or {}).get('result') or {}).get('result')
            if not isinstance(res, dict) or not isinstance(res.get('usage'), dict):
                continue
            u = res['usage']
            out['calls'] += 1
            out['input'] += int(u.get('input_tokens') or 0)
            out['cached'] += int(u.get('cached_input_tokens') or 0)
            out['output'] += int(u.get('output_tokens') or 0)
            out['last_finish_reason'] = str(res.get('finish_reason') or '')
            # A final answer: the call did not end on a tool call and carries
            # answer text (reasoning parts don't count).
            answer = [p for p in (res.get('parts') or [])
                      if isinstance(p, dict) and p.get('type') != 'reasoning']
            out['last_has_text'] = res.get('finish_reason') != 'tool_call' and any(
                (p.get('text') or '').strip()
                or any(isinstance(c, dict) and (c.get('text') or '').strip()
                       for c in (p.get('content') or []))
                for p in answer)
    return out if out['calls'] else None


def _call_vibe_cli(model_id, prompt, max_tokens=4096, *, project_path=None,
                   exec_id=None, caller=''):
    """Route through the Vibe CLI. Tool support (Read/Edit/Write/Bash) gated by
    .vibe/config.toml. Always bills to the Mistral API key's monthly budget
    (Le Chat Pro subscription).

    cwd=project_path so the CLI auto-discovers <project>/.vibe/config.toml.
    --agent accept-edits enables Edit/Write without prompts; Bash stays gated
    by the config file (groups A+B+C globally, D per project)."""
    import subprocess, json, shutil, os
    if not shutil.which('vibe'):
        raise RuntimeError('vibe CLI not found. Install Mistral Vibe: https://github.com/mistralai/vibe')
    if not project_path:
        raise VibeCLIError('project_path is required for Vibe CLI calls')

    if not os.path.isdir(project_path):
        raise VibeCLIError(f'project_path does not exist or is not a directory: {project_path}')

    _timeout = getattr(agent_config, 'VIBE_CLI_TIMEOUT_SECS', 2700)

    @retry(
        stop=stop_after_attempt(getattr(agent_config, 'VIBE_CLI_RETRY_ATTEMPTS', 3)),
        wait=wait_exponential(multiplier=1, min=1, max=10),
        retry=retry_if_exception_type(VIBE_CLI_RETRYABLE_ERRORS),
        reraise=True,
    )
    def _run_vibe_cli(cmd, env, cwd):
        # If the execution was cancelled while we were waiting to retry, stop
        # immediately instead of re-spawning the CLI (regression: a cancelled
        # task kept re-running via the retry loop, leaving the slot stuck).
        if _execution_cancelled(exec_id, project_path):
            raise ExecutionCancelledError('execution cancelled')
        # stdin=DEVNULL: vibe's get_prompt_from_stdin() calls sys.stdin.read()
        # unconditionally (even with --prompt); if the parent's fd 0 is a
        # non-TTY (nohup / systemd / closed fd), vibe's pre-read setup can
        # invalidate fd 0 → OSError [Errno 9] Bad file descriptor. Explicit
        # DEVNULL gives vibe a clean, always-EOF stdin regardless of how
        # AIngel was launched. Mirrors _call_claude_cli / _call_codex_cli.
        proc = subprocess.Popen(cmd, stdin=subprocess.DEVNULL,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                text=True, env=env, cwd=cwd,
                                start_new_session=True)
        # Record the child PID so the /cancel endpoint and orphan sweep can
        # identify/kill the actual provider process if it hangs.
        if exec_id is not None:
            try:
                import agent_db as db
                db.set_execution_pid(exec_id, proc.pid, project_path)
            except Exception:
                pass
        try:
            stdout, stderr = proc.communicate(timeout=_timeout)
        except subprocess.TimeoutExpired:
            _kill_process_group(proc)
            proc.communicate()
            # Not a RuntimeError, so the retry loop stops here. Short message:
            # TimeoutExpired's own str() embeds the whole argv (the prompt).
            raise VibeCLITimeout(
                f'Vibe CLI exceeded the {_timeout // 60}-min run limit '
                f'(VIBE_CLI_TIMEOUT_SECS={_timeout}); run stopped, not retried.')
        # The cancel endpoint may have killed the child mid-run; treat that as
        # a terminal cancellation, not a retryable transport error.
        if _execution_cancelled(exec_id, project_path):
            raise ExecutionCancelledError('execution cancelled')
        # Mimic subprocess.run's CompletedProcess for the rest of the function
        import subprocess as _sp
        result = _sp.CompletedProcess(cmd, proc.returncode, stdout, stderr)
        if result.returncode != 0:
            err = (result.stderr or '').strip() or (result.stdout or '').strip()
            # Vibe exits non-zero when the model exhausts --max-turns without a
            # final answer, emitting `<vibe_stop_event>Turn limit of N
            # reached</vibe_stop_event>`. The conversation so far is still in
            # stdout — recover it instead of discarding everything and hard-
            # failing the task (regression: task #10000698, a client project, which
            # failed with tokens_input=0/tokens_output=0 and no partial output
            # despite ~50 turns of real work). We surface a clear note so the
            # caller knows the run was incomplete.
            if 'Turn limit' in err and 'reached' in err:
                result._vibe_turn_limit = True  # type: ignore[attr-defined]
                return result
            raise RuntimeError(f'vibe CLI error (exit {result.returncode}): {err}')
        return result

    if not MISTRAL_VIBE_KEY:
        raise ValueError('MISTRAL_VIBE_KEY not set in .env (required for Vibe CLI — see CLAUDE.md Mistral routing)')
    # Scrubbed env: only the Vibe provider key(s) are forwarded, not the whole
    # server environment (session secret, DAV token, other provider keys, …).
    _vibe_extra = {
        'MISTRAL_VIBE_KEY': MISTRAL_VIBE_KEY,
        # Vibe's built-in `mistral` provider resolves credentials from
        # MISTRAL_API_KEY. SuperAgent stores the Pro/Vibe key as
        # MISTRAL_VIBE_KEY, so bridge it in without duplicating secrets in
        # ~/.vibe/.env.
        'MISTRAL_API_KEY': MISTRAL_VIBE_KEY,
        # Vibe selects its model from `active_model`; VIBE_* overrides the
        # user's ~/.vibe/config.toml for this call.
        'VIBE_ACTIVE_MODEL': _VIBE_MODEL_ID_MAP.get(model_id, model_id),
    }
    if MISTRAL_ORG_KEY:
        _vibe_extra['MISTRAL_ORG_KEY'] = MISTRAL_ORG_KEY
    env = agent_config.cli_subprocess_env(_vibe_extra)

    # Pause state (item 16 Phase 3): a task run on the Vibe route can pause at
    # its turn/time limit and be continued later (the prompt is replayed with a
    # continuation block — Vibe has no headless resume). Other callers (chats,
    # H3, guide, autopilot) never set the scope and keep the old behaviour:
    # recovered text + VIBE_TURN_LIMIT_MARKER.
    _pause = current_pause_scope()
    _resume = (_pause or {}).get('resume') if _pause else None
    _cs = (_resume or {}).get('cli_session') or {}
    _resuming = bool(_resume and _cs.get('kind') == 'vibe')

    # Build the guardrail-prefixed prompt BEFORE constructing cmd, so the
    # final prompt is the single source of truth and we send it exactly once.
    deny_patterns = _get_deny_patterns_for_system_prompt(project_path)
    _deny_prefix = ''
    if deny_patterns:
        _deny_prefix = (
            "IMPORTANT: Do NOT run these commands under any circumstances:\n"
            f"{deny_patterns}\n\n"
            "If you need to run any of these, stop and explain why first.\n\n"
        )

    if _resuming:
        # The Vibe CLI has no headless resume. `--resume` / `--continue` are
        # mutually exclusive with `--prompt` (clap rejects the pair) and only
        # open the interactive TUI; `VIBE_CLI=python` accepts the pair but runs
        # the classic harness and rotates the session journal (verified live on
        # 2026-10-29). So a continued block is a FRESH Vibe session that gets
        # the task prompt again, plus what the previous block already did.
        _base_prompt = _deny_prefix + prompt
        _room = max(800, VIBE_PROMPT_MAX_BYTES
                    - len(_base_prompt.encode('utf-8')) - 500)
        sent_prompt = _base_prompt + _vibe_continuation_block(_resume, room=_room)
        sent_prompt, _prompt_truncated = _fit_vibe_prompt(sent_prompt, caller=caller)
    else:
        prompt = _deny_prefix + prompt
        # Cap the prompt so it fits on the argv. vibe has no --prompt-file flag and
        # stdin is unusable (see stdin=DEVNULL / EBADF), so an oversized prompt would
        # raise `OSError [Errno 7] Argument list too long` before vibe runs. Chats keep
        # the tail (newest context); task runs are REFUSED — their instructions are at
        # the front and must never be truncated (see _fit_vibe_prompt / RP-114-E1).
        prompt, _prompt_truncated = _fit_vibe_prompt(prompt, caller=caller)
        sent_prompt = prompt

    cmd = [
        'vibe',
        '--prompt', sent_prompt,
        '--agent', 'accept-edits',     # MUST pass — programmatic default is 'auto-approve'
        '--auto-approve',              # approve all tool calls without prompting (programmatic mode)
        '--output', 'json',
        '--max-turns', str(VIBE_MAX_TURNS),
        '--max-price', str(VIBE_MAX_PRICE),
        '--trust',                     # trust project dir so .vibe/config.toml is loaded
    ]
    _guide = current_guide_scope()
    if _guide:
        # Guide mode: the read-only profile, and NO --auto-approve — headless
        # Vibe then denies every call the profile doesn't allow.
        cmd[cmd.index('accept-edits')] = _ensure_vibe_guide_agent(_guide['write_dir'])
        cmd.remove('--auto-approve')
    assert '--agent' in cmd, '_call_vibe_cli: --agent must be present (programmatic default is auto-approve)'
    # `bypass_tool_permissions` is a Vibe config field (vibe/core/config/_settings.py);
    # any field can be overridden via VIBE_<UPPER_CASE_NAME> per Vibe docs.
    if VIBE_SKIP_PERMISSIONS and not _guide:
        env['VIBE_BYPASS_TOOL_PERMISSIONS'] = 'true'

    _t0 = time.time()
    try:
        result = _run_vibe_cli(cmd, env, project_path)
    except VibeCLITimeout:
        if not _pause:
            raise
        # Time-limit pause: the run was SIGKILLed, so stdout is unusable. The
        # session journal holds the usage and the conversation written so far.
        vibe_usage = None
        try:
            vibe_usage = _vibe_session_usage(project_path, prompt, _t0, time.time())
        except Exception as e:
            _log.warning('Vibe usage lookup failed at the time limit: %s', e)
        _sid = _pick_vibe_session(vibe_usage)
        if not _sid:
            raise   # no resumable session — today's behaviour (fail the run)
        _seg_in = int((vibe_usage or {}).get('input') or 0)
        _seg_out = int((vibe_usage or {}).get('output') or 0)
        _seg, _ = _vibe_journal_transcript(vibe_session_dir(_sid))
        _raise_limit('time', _cli_checkpoint(
            kind='vibe', session_id=_sid, reason='time',
            turns=int((vibe_usage or {}).get('calls') or 0),
            elapsed_s=time.time() - _t0, status_text=_vibe_status_line(_seg),
            transcript=_transcript_seed(_resume) + _seg, model_id=model_id,
            seg_in=_seg_in, seg_out=_seg_out), _seg_in, _seg_out)
    vibe_turn_limit = getattr(result, '_vibe_turn_limit', False)
    try:
        vibe_usage = _vibe_session_usage(project_path, prompt, _t0, time.time())
    except Exception as e:
        _log.warning('Vibe session usage lookup failed: %s', e)
        vibe_usage = None
    # Vibe 2.26 stops at --max-turns with exit 0, so the non-zero-exit check in
    # _run_vibe_cli no longer sees it: exec 20001220 hit 80 calls and came back
    # with an empty reply and no marker. A run can ALSO end mid-work far below
    # the budget: the last model call spends its whole output budget on
    # reasoning (finish_reason 'other', no text part, no tool call), Vibe
    # closes the session with exit 0, and the parser falls back to an earlier
    # assistant message — so an unfinished run looks 'done' (regression: exec
    # 20001441/20001442 on task 10001301, 13–16 of 80 calls, deliverable never
    # written). Any last call that is neither a tool call nor a real answer is
    # an incomplete run. A bare tool call as the very last record is the
    # documented turn-limit shape and keeps its own handling (simulation-
    # detector exemption), so below the budget it is NOT flagged here.
    _exhausted = bool(vibe_usage and vibe_usage['calls'] >= VIBE_MAX_TURNS)
    if (vibe_usage and not vibe_usage['last_has_text']
            and (vibe_usage.get('last_finish_reason') != 'tool_call' or _exhausted)):
        vibe_turn_limit = True

    def _pause_or_mark(_text):
        """Turn-limit handling: pause with a checkpoint, or append the marker.

        Pausing needs the executor's scope (task runs only) and a session id
        that identifies the journal to read back; without either, the old
        marker behaviour is kept."""
        _sid = _pick_vibe_session(vibe_usage)
        if vibe_turn_limit and _pause and _sid:
            _seg_in = int((vibe_usage or {}).get('input') or 0)
            _seg_out = int((vibe_usage or {}).get('output') or 0)
            _seg, _ = _vibe_journal_transcript(vibe_session_dir(_sid))
            _raise_limit('turns', _cli_checkpoint(
                kind='vibe', session_id=_sid, reason='turns',
                turns=int((vibe_usage or {}).get('calls') or 0),
                elapsed_s=time.time() - _t0, status_text=_vibe_status_line(_seg, _text),
                transcript=_transcript_seed(_resume) + _seg, model_id=model_id,
                seg_in=_seg_in, seg_out=_seg_out), _seg_in, _seg_out)
        if vibe_turn_limit:
            _text = ((_text or '').rstrip()
                     or '_(The model left no final text: its last action was a tool call.)_')
            if _exhausted:
                _why = (f"{VIBE_TURN_LIMIT_MARKER} ({VIBE_MAX_TURNS} turns) before "
                        "the model produced a final answer.")
            else:
                _why = (f"{VIBE_TURN_LIMIT_MARKER} — the run ended without a final "
                        "answer: the last model response carried only reasoning "
                        "(no text, no tool call).")
            _text += (
                f"\n\n---\n⚠️ **{_why}** The text above is the last "
                "assistant message; files it wrote may be incomplete. The task is "
                "likely too large for one run (split it into smaller tasks) or "
                "needs tools the Vibe CLI doesn't provide (e.g. Proton MCP email "
                "tools, external web research)."
            )
        return _text

    try:
        data = json.loads(result.stdout)
        # Vibe returns an array of messages; use the last assistant message that
        # carries text. Never fall back to the raw stdout: it is the whole
        # conversation, system prompt included, and that prompt's "do not emit
        # <bash>…</bash>" rule trips the simulation detector (exec 20001185,
        # task #10001192: a turn-limit run whose last message was a bare tool
        # call was failed as "simulated a tool call in text").
        if isinstance(data, list):
            text = ''
            for msg in reversed(data):
                if isinstance(msg, dict) and msg.get('role') == 'assistant':
                    text = _flatten_content(msg.get('content')).strip()
                    if text:
                        break
        elif isinstance(data, dict):
            if data.get('is_error'):
                raise RuntimeError(f'vibe CLI returned error: {data.get("result", "unknown error")}')
            text = _flatten_content(data.get('result')) or result.stdout.strip()
        else:
            text = result.stdout.strip()

        # Phase 3: a paused run raises instead of finishing; otherwise the
        # partial conversation gets the marker (user-visible via the output file).
        text = _pause_or_mark(text)

        # Tokens come from this call's own session journal (see
        # _vibe_session_usage); cost from Cordée's PRICING, never Vibe's own
        # estimate — Vibe models bill to the subscription and are priced at 0.
        # Heuristic fallback (1 token ≈ 4 chars) only when the session can't be
        # identified, logged so the drift is visible. A continued block opens a
        # fresh session, so its totals never include the earlier parts.
        if vibe_usage:
            tok_in = int(vibe_usage['input'])
            tok_out = int(vibe_usage['output'])
        else:
            tok_in = max(1, len(sent_prompt) // 4)
            tok_out = max(1, len(result.stdout) // 4)
            _log.warning('Vibe CLI: session not identified; heuristic tokens (in=%d, out=%d)',
                         tok_in, tok_out)
        cost = _pricing_cost(model_id, tok_in, tok_out)
    except (json.JSONDecodeError, ValueError) as e:
        _log.warning(f'Failed to parse Vibe CLI output: {e}')
        text = _pause_or_mark(result.stdout.strip())
        if vibe_usage:
            tok_in = int(vibe_usage['input'])
            tok_out = int(vibe_usage['output'])
        else:
            tok_in  = max(1, len(sent_prompt) // 4)
            tok_out = max(1, len(text) // 4)
        cost = _pricing_cost(model_id, tok_in, tok_out)
    return text, tok_in, tok_out, cost


def _get_deny_patterns_for_system_prompt(project_path):
    """Build the bash deny guardrail prefix from project permissions.
    Returns a string like:
        - rm, sudo, chmod, git push, git reset --hard, ...
    """
    if not project_path:
        return ""
    try:
        from agent_permissions import get_deny_patterns_for_project
        patterns = get_deny_patterns_for_project(project_path)
        if not patterns:
            return ""
        return "- " + "\n- ".join(sorted(patterns))
    except ImportError:
        _log.warning('agent_permissions module not available for deny patterns')
        return ""
    except Exception as e:
        _log.warning(f'_get_deny_patterns_for_system_prompt failed: {e}')
        return ""


def _call_claude_cli(model_id, prompt, max_tokens=4096, *, project_path=None, auth_mode='pro', exec_id=None):
    """Route through the claude CLI. Both auth modes get identical tool support
    (Read/Edit/Write/Bash, gated by .claude/settings.json); they differ only in
    who gets billed.

    auth_mode='pro' — strips ANTHROPIC_API_KEY from subprocess env so the CLI
        falls back to OAuth (Pro/Max subscription). No API credit charge.
    auth_mode='api' — keeps ANTHROPIC_API_KEY in env so the CLI bills via the
        API key (pay-as-you-go API credits).

    cwd=project_path so the CLI auto-discovers <project>/.claude/settings.json.
    --permission-mode acceptEdits enables Edit/Write without prompts; Bash
    stays gated by the .claude/settings.json allow list (groups A+B+C
    globally, D per project)."""
    import subprocess, json, shutil, os
    if not shutil.which('claude'):
        raise RuntimeError('claude CLI not found. Install Claude Code: https://claude.ai/code')
    # Failure-driven health: never spawn the CLI for a provider we already know
    # is unusable (no credit / subscription disabled). A probe run from Create
    # Task or a model-list refresh clears this automatically when it recovers.
    _degraded = agent_config.provider_degraded('anthropic')
    if _degraded:
        raise RuntimeError(
            f'Claude is currently unavailable ({_degraded}). Switch this '
            f'task/chat to an available model, or restore Anthropic billing. '
            f'The model list re-checks Claude automatically when you open a task.')
    if not project_path:
        _log.warning('_call_claude_cli: project_path is empty; inheriting server cwd')

    if auth_mode == 'api':
        if not ANTHROPIC_API_KEY:
            raise ValueError('ANTHROPIC_API_KEY not set in .env (required for api mode)')
        # Scrubbed env: only the Anthropic key is forwarded.
        env = agent_config.cli_subprocess_env({'ANTHROPIC_API_KEY': ANTHROPIC_API_KEY})
    elif auth_mode == 'pro':
        # Scrubbed env, no API key — the CLI falls back to its OAuth login.
        env = agent_config.cli_subprocess_env()
    else:
        raise ValueError(f'auth_mode must be "pro" or "api", got {auth_mode!r}')

    # Pause state (item 16 Phase 3): a pausable task run persists a session we
    # pin ourselves (`--session-id`), so the id survives even a SIGKILL at the
    # time limit. Chats/H3/guide/autopilot keep session persistence OFF — no
    # transcript accumulation outside task runs, no resumable artifacts.
    _pause = current_pause_scope()
    _resume = (_pause or {}).get('resume') if _pause else None
    _cs = (_resume or {}).get('cli_session') or {}
    _resuming = bool(_cs.get('kind') == 'claude' and _cs.get('session_id'))
    _session_id = _cs.get('session_id') if _resuming else None
    if _pause and not _session_id:
        import uuid
        _session_id = str(uuid.uuid4())
    _prior = _transcript_seed(_resume) if _resuming else []
    _sent_prompt = continue_message(_resume.get('note')) if _resuming else prompt
    _t0 = time.time()

    cmd = [
        'claude', '--print',
        "--model", model_id,
        '--output-format', 'json',
        '--permission-mode', 'acceptEdits',
    ]
    if _resuming:
        cmd += ['--resume', _session_id]
    elif _pause:
        # Task run that may pause: keep the session on disk and cap the turns.
        cmd += ['--session-id', _session_id, '--max-turns', str(CLAUDE_MAX_TURNS)]
    else:
        cmd.append('--no-session-persistence')
    if current_guide_scope():
        # Guide mode: plan mode is read-only (no edits, no shell side effects).
        cmd[cmd.index('acceptEdits')] = 'plan'
    elif CLAUDE_CODE_SKIP_PERMISSIONS:
        cmd.append('--dangerously-skip-permissions')
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, text=True,
                            env=env, cwd=project_path or None,
                            start_new_session=True)
    if exec_id is not None:
        try:
            import agent_db as db
            db.set_execution_pid(exec_id, proc.pid, project_path)
        except Exception:
            pass
    try:
        stdout, stderr = proc.communicate(input=_sent_prompt,
                                          timeout=CLAUDE_CLI_TIMEOUT_SECS)
    except subprocess.TimeoutExpired:
        _kill_process_group(proc)
        try:
            proc.communicate()
        except Exception:
            pass
        if not _pause:
            raise
        # Time-limit pause: the session id is ours (pinned above), so the run
        # resumes from it. The killed segment's tokens never reached the
        # envelope — recorded as 0 rather than invented.
        _raise_limit('time', _cli_checkpoint(
            kind='claude', session_id=_session_id, reason='time',
            turns=0, elapsed_s=time.time() - _t0, status_text='',
            transcript=list(_prior), model_id=model_id, seg_in=0, seg_out=0), 0, 0)
    import subprocess as _sp
    result = _sp.CompletedProcess(cmd, proc.returncode, stdout, stderr)

    def _pause_on_max_turns(data):
        """Turn-limit pause: `--max-turns` early-exits with subtype
        error_max_turns (and a non-zero exit code), which is not a failure.
        The `result` text is the partial narration the user and H3 can use."""
        _usage = data.get('usage') or {}
        _seg_in = int(_usage.get('input_tokens') or 0)
        _seg_out = int(_usage.get('output_tokens') or 0)
        _partial = (data.get('result') or '').strip()
        _raise_limit('turns', _cli_checkpoint(
            kind='claude', session_id=_session_id, reason='turns',
            turns=int(data.get('num_turns') or 0) or CLAUDE_MAX_TURNS,
            elapsed_s=time.time() - _t0, status_text=_partial,
            transcript=list(_prior) + ([_partial] if _partial else []),
            model_id=model_id, seg_in=_seg_in, seg_out=_seg_out),
            _seg_in, _seg_out)

    if result.returncode != 0:
        # The envelope is still on stdout: a turn-limit stop must pause, not
        # fail, so inspect it before the generic error path.
        _env = _load_result_envelope(result.stdout)
        if _pause and _env and (
                (_env.get('subtype') or '') == 'error_max_turns'
                or 'Reached max turns' in str(_env.get('result') or '')):
            _pause_on_max_turns(_env)
        err = result.stderr.strip() or result.stdout.strip()
        _reason = agent_config.classify_auth_error(err)
        if _reason:
            agent_config.mark_provider_degraded('anthropic', _reason)
            raise RuntimeError(
                f'Claude is currently unavailable ({_reason}). Switch this '
                f'task/chat to an available model, or restore Anthropic billing. '
                f'Claude CLI said: {err[:400]}')
        raise RuntimeError(f'claude CLI error (exit {result.returncode}): {err}')
    try:
        data = _load_result_envelope(result.stdout)
        if not data:
            raise RuntimeError(f'claude CLI returned malformed JSON: {result.stdout.strip() or "empty output"}')
        # Phase 3: same pause when the CLI exits 0 but flags the turn limit.
        _max_turns_hit = (
            (data.get('subtype') or '') == 'error_max_turns'
            or 'Reached max turns' in str(data.get('result') or ''))
        if _max_turns_hit and _pause:
            _pause_on_max_turns(data)
        if data.get('is_error'):
            raise RuntimeError(f'claude CLI returned error: {data.get("result", "unknown error")}')
        denials = data.get('permission_denials') or []
        text = (data.get('result') or '').strip()
        # `permission_denials` is a *log* of tool calls blocked during the run,
        # NOT a task-level failure. Claude Code routinely tries a command, gets
        # denied (e.g. the intentionally-blocked `systemctl restart`), and routes
        # around it to finish the task. Only treat denials as fatal when Claude
        # produced no usable result at all — otherwise the work is done and we
        # just append a note about what was blocked.
        if not text:
            if denials:
                detail = _summarize_permission_denials(denials)
                raise RuntimeError(
                    'claude CLI permission denied (no output produced)'
                    + (f': {detail}' if detail else '')
                )
            stop_reason = data.get('stop_reason') or data.get('terminal_reason') or 'unknown'
            raise RuntimeError(f'claude CLI returned an empty result (stop_reason={stop_reason})')
        if denials:
            detail = _summarize_permission_denials(denials)
            text += (
                '\n\n---\n_Note: some tool calls were blocked by the permission '
                f'system during this run (non-fatal): {detail}_'
            )
        cost = float(data.get('total_cost_usd', data.get('cost_usd', 0.0)))
        usage = data.get('usage', {})
        tok_in  = usage.get('input_tokens') or max(1, len(prompt) // 4)
        tok_out = usage.get('output_tokens') or max(1, len(text) // 4)
    except (json.JSONDecodeError, ValueError):
        text = result.stdout.strip()
        cost = 0.0
        tok_in  = max(1, len(prompt) // 4)
        tok_out = max(1, len(text) // 4)
    return text, tok_in, tok_out, cost


